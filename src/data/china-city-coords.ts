/** 按 省|市 → 市 → 省 的顺序查兜底坐标，查不到返回 null */
export function lookupCityCoords(
	province: string,
	city?: string,
): [number, number] | null {
	const provinceKey = province?.trim();
	if (!provinceKey) return null;

	const cityKey = city?.trim();
	if (cityKey) {
		const full = chinaCityCoords[`${provinceKey}|${cityKey}`];
		if (full) return full;
		const byCity = chinaCityCoords[cityKey];
		if (byCity) return byCity;
	}

	return chinaCityCoords[provinceKey] ?? null;
}
